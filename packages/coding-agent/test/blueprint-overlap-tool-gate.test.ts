import assert from "node:assert/strict";
import { fauxAssistantMessage, fauxToolCall } from "@bastani/pi-ai/compat";
import type { AgentToolCallOutcome, AgentToolResult } from "@earendil-works/pi-agent-core";
import { Type } from "typebox";
import { afterEach, describe, test } from "vitest";
import type { ExtensionFactory, ToolDefinition } from "../src/core/extensions/index.ts";
import {
	awaitBlueprintReady,
	blueprintBuildPending,
	holdToolsUntilBuilt,
} from "../src/core/resume/blueprint/barrier.ts";
import { createHarness, type Harness } from "./suite/harness.ts";

const cleanups: Array<() => Promise<void> | void> = [];
afterEach(async () => {
	while (cleanups.length > 0) await cleanups.pop()?.();
});

async function harnessWith(options: Parameters<typeof createHarness>[0]): Promise<Harness> {
	const harness = await createHarness(options);
	cleanups.push(() => harness.cleanup());
	return harness;
}

/** Holds the tools of `harness`'s session for a build that settles with `report`, or never when it is omitted. */
function holdFor(harness: Harness, report?: string): void {
	const sessionId = harness.sessionManager.getSessionId();
	holdToolsUntilBuilt(sessionId, report === undefined ? new Promise(() => {}) : Promise.resolve(report));
	cleanups.push(async () => {
		holdToolsUntilBuilt(sessionId, Promise.resolve(undefined));
		await awaitBlueprintReady(sessionId);
	});
}

/** A tool that declares `writesFiles`, so it waits for the build, and whose calls end when the test releases them. */
function generator() {
	const started: string[] = [];
	const releases = new Map<string, () => void>();
	const definition: ToolDefinition = {
		name: "generate",
		label: "Generate",
		description: "Generates files",
		parameters: Type.Object({}),
		writesFiles: true,
		execute: async (toolCallId) => {
			started.push(toolCallId);
			await new Promise<void>((resolve) => releases.set(toolCallId, resolve));
			return { content: [{ type: "text", text: `generated by ${toolCallId}` }], details: undefined };
		},
	};
	return { definition, started, release: (toolCallId: string) => releases.get(toolCallId)?.() };
}

function resultText(harness: Harness, toolCallId: string): string {
	const result = harness.session.messages.find(
		(message) => message.role === "toolResult" && message.toolCallId === toolCallId,
	);
	if (result === undefined || result.role !== "toolResult") throw new Error(`no result for ${toolCallId}`);
	return result.content.flatMap((part) => (part.type === "text" ? [part.text] : [])).join("\n");
}

async function until(condition: () => boolean, what: string): Promise<void> {
	const deadline = Date.now() + 20_000;
	while (!condition()) {
		if (Date.now() > deadline) throw new Error(`timed out waiting for ${what}`);
		await new Promise((resolve) => setTimeout(resolve, 10));
	}
}

describe("the overlapped blueprint build's tool gate (#4748)", () => {
	test("interrupting a nested tool call stops its wait for the build at once, and the build goes on (#4748)", async () => {
		/** How long the nested call may take to give up once interrupted; the build never ends in this test. */
		const INTERRUPTED_WITHIN_MS = 5_000;
		const child = generator();
		let nested: AgentToolCallOutcome | "still waiting" | undefined;
		const parent: ExtensionFactory = (pi) => {
			pi.registerTool(child.definition);
			pi.registerTool({
				name: "parent",
				label: "Parent",
				description: "Runs generate as a nested call and interrupts it",
				concurrency: "exclusive",
				parameters: Type.Object({}),
				execute: async (_id, _args, _signal, _update, ctx): Promise<AgentToolResult<undefined>> => {
					const controller = new AbortController();
					const call = ctx.executeTool("generate", {}, { signal: controller.signal });
					setTimeout(() => controller.abort(new Error("interrupted")), 100);
					nested = await Promise.race([
						call,
						new Promise<"still waiting">((resolve) =>
							setTimeout(() => resolve("still waiting"), INTERRUPTED_WITHIN_MS),
						),
					]);
					return { content: [{ type: "text", text: "parent done" }], details: undefined };
				},
			});
		};
		const harness = await harnessWith({ extensionFactories: [parent], initialActiveToolNames: ["parent"] });
		holdFor(harness);
		harness.setResponses([
			fauxAssistantMessage([fauxToolCall("parent", {}, { id: "p-1" })], { stopReason: "toolUse" }),
			fauxAssistantMessage("done"),
		]);

		await harness.session.prompt("run parent");

		assert.notEqual(nested, "still waiting", "the interrupted nested call stopped waiting");
		assert.equal(typeof nested === "object" && nested.isError, true);
		assert.deepEqual(child.started, [], "the interrupted nested call never ran");
		assert.equal(blueprintBuildPending(harness.sessionManager.getSessionId()), true, "the build goes on");
	});

	test("two sessions in one process each get their own build report, even for the same tool call id (#4748)", async () => {
		const runs = [
			{ tool: generator(), report: "report of session A" },
			{ tool: generator(), report: "report of session B" },
		];
		const harnesses: Harness[] = [];
		for (const run of runs) {
			const harness = await harnessWith({ customTools: [run.tool.definition] });
			holdFor(harness, run.report);
			harness.setResponses([
				fauxAssistantMessage([fauxToolCall("generate", {}, { id: "same-id" })], { stopReason: "toolUse" }),
				fauxAssistantMessage("done"),
			]);
			harnesses.push(harness);
		}

		const prompts = harnesses.map((harness) => harness.session.prompt("generate"));
		await until(() => runs.every((run) => run.tool.started.length === 1), "both calls to start");
		for (const run of runs) run.tool.release("same-id");
		await Promise.all(prompts);

		assert.equal(resultText(harnesses[0]!, "same-id"), "report of session A\ngenerated by same-id");
		assert.equal(resultText(harnesses[1]!, "same-id"), "report of session B\ngenerated by same-id");
	});

	for (const [how, outcome] of [
		["is blocked by an extension", { block: true, reason: "not this one" }],
		["fails in an extension's tool_call handler", new Error("not this one")],
	] as const) {
		test(`a call that waited for the build but ${how} leaves its report to the next call that waits (#4748)`, async () => {
			const tool = generator();
			const stopFirst: ExtensionFactory = (pi) => {
				pi.on("tool_call", (event) => {
					if (event.toolCallId !== "g-1") return undefined;
					if (outcome instanceof Error) throw outcome;
					return outcome;
				});
			};
			const harness = await harnessWith({ customTools: [tool.definition], extensionFactories: [stopFirst] });
			holdFor(harness, "the build report");
			harness.setResponses([
				fauxAssistantMessage([fauxToolCall("generate", {}, { id: "g-1" })], { stopReason: "toolUse" }),
				fauxAssistantMessage([fauxToolCall("generate", {}, { id: "g-2" })], { stopReason: "toolUse" }),
				fauxAssistantMessage("done"),
			]);

			const prompt = harness.session.prompt("generate");
			await until(() => tool.started.length === 1, "the second call to start");
			tool.release("g-2");
			await prompt;

			assert.deepEqual(tool.started, ["g-2"]);
			assert.match(resultText(harness, "g-1"), /not this one/);
			assert.equal(resultText(harness, "g-2"), "the build report\ngenerated by g-2");
		});
	}
});
